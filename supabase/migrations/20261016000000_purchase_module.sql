-- ─── 1. Aturan jabatan ───
CREATE TABLE IF NOT EXISTS public.purchase_jabatan_rules (
  jabatan_id integer PRIMARY KEY REFERENCES public.jabatan(id) ON DELETE CASCADE,
  can_request boolean NOT NULL DEFAULT false,
  can_manage boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by uuid
);

-- ─── 2. Pengajuan PO ───
CREATE TABLE IF NOT EXISTS public.purchase_orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  po_no text NOT NULL UNIQUE,
  title text NOT NULL,
  detail text NOT NULL,
  amount bigint NOT NULL CHECK (amount > 0),
  vendor_name text NOT NULL,
  bank_name text NOT NULL,
  account_number text NOT NULL,
  account_name text NOT NULL,
  purpose text NOT NULL,
  submitted_by uuid NOT NULL,
  requester_employee_id text REFERENCES public.pegawai(id) ON DELETE SET NULL,
  requester_name text NOT NULL,
  requester_jabatan_id integer REFERENCES public.jabatan(id) ON DELETE SET NULL,
  requester_jabatan_nama text NOT NULL DEFAULT '',
  process_status text NOT NULL DEFAULT 'po_masuk'
    CHECK (process_status IN ('po_masuk','po_diterima','on_process','waiting_list','pending_payment','non_approve','cancel')),
  total_paid bigint NOT NULL DEFAULT 0 CHECK (total_paid >= 0),
  submitted_at timestamptz NOT NULL DEFAULT now(),
  idempotency_key text UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_submitted_at ON public.purchase_orders (submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_submitted_by ON public.purchase_orders (submitted_by);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_status ON public.purchase_orders (process_status);
CREATE INDEX IF NOT EXISTS idx_purchase_orders_jabatan ON public.purchase_orders (requester_jabatan_id);

-- ─── 3. Pembayaran / cicilan (dibuat sebelum lampiran karena dirujuk FK) ───
CREATE TABLE IF NOT EXISTS public.purchase_order_payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE CASCADE,
  payment_date date NOT NULL,
  amount bigint NOT NULL CHECK (amount > 0),
  notes text,
  idempotency_key text UNIQUE,
  recorded_by uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_purchase_payments_order ON public.purchase_order_payments (order_id);
CREATE INDEX IF NOT EXISTS idx_purchase_payments_date ON public.purchase_order_payments (payment_date);

-- ─── 4. Lampiran ───
CREATE TABLE IF NOT EXISTS public.purchase_order_attachments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE CASCADE,
  file_name text NOT NULL,
  mime_type text NOT NULL,
  file_size bigint NOT NULL CHECK (file_size > 0),
  storage_path text NOT NULL,
  kind text NOT NULL DEFAULT 'bukti' CHECK (kind IN ('bukti', 'pembayaran')),
  payment_id bigint REFERENCES public.purchase_order_payments(id) ON DELETE CASCADE,
  uploaded_by uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_purchase_attachments_order ON public.purchase_order_attachments (order_id);

-- ─── 5. Timeline / riwayat ───
CREATE TABLE IF NOT EXISTS public.purchase_order_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.purchase_orders(id) ON DELETE CASCADE,
  event_type text NOT NULL CHECK (event_type IN ('created','edited','status_change','note','payment','attachment')),
  from_status text,
  to_status text,
  note text,
  actor_id uuid,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_purchase_events_order ON public.purchase_order_events (order_id, created_at);

-- ─── 6. Counter nomor PO per periode ───
CREATE TABLE IF NOT EXISTS public.purchase_order_counters (
  period text PRIMARY KEY CHECK (period ~ '^[0-9]{4}-[0-9]{2}$'),
  last_seq integer NOT NULL DEFAULT 0
);

