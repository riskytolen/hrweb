-- ─── 8. Nomor PO otomatis, aman untuk pengajuan bersamaan ───
CREATE OR REPLACE FUNCTION public.next_purchase_order_no()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_period text := to_char(now(), 'YYYY-MM');
  v_seq integer;
BEGIN
  INSERT INTO public.purchase_order_counters (period, last_seq)
  VALUES (v_period, 1)
  ON CONFLICT (period) DO UPDATE SET last_seq = public.purchase_order_counters.last_seq + 1
  RETURNING last_seq INTO v_seq;

  RETURN 'PO/' || substring(v_period, 1, 4) || '/' || substring(v_period, 6, 2) || '/' || lpad(v_seq::text, 5, '0');
END;
$$;

REVOKE ALL ON FUNCTION public.next_purchase_order_no() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.next_purchase_order_no() TO service_role;

-- ─── 9. Pembayaran transaksional (kunci baris order, cegah overpay) ───
CREATE OR REPLACE FUNCTION public.record_purchase_payment(
  p_order_id bigint,
  p_payment_date date,
  p_amount bigint,
  p_notes text,
  p_actor uuid,
  p_idempotency_key text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_status text;
  v_amount bigint;
  v_paid bigint;
  v_payment_id bigint;
BEGIN
  IF p_amount IS NULL OR p_amount <= 0 THEN
    RAISE EXCEPTION 'PURCHASE_PAYMENT_AMOUNT:nominal pembayaran harus lebih dari nol';
  END IF;
  IF p_payment_date IS NULL THEN
    RAISE EXCEPTION 'PURCHASE_PAYMENT_DATE:tanggal pembayaran wajib diisi';
  END IF;

  SELECT process_status, amount, total_paid
    INTO v_status, v_amount, v_paid
    FROM public.purchase_orders
    WHERE id = p_order_id
    FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'PURCHASE_ORDER_NOT_FOUND:PO tidak ditemukan';
  END IF;
  IF v_status IN ('non_approve', 'cancel') THEN
    RAISE EXCEPTION 'PURCHASE_ORDER_CLOSED:PO sudah ditolak/dibatalkan';
  END IF;
  IF v_paid + p_amount > v_amount THEN
    RAISE EXCEPTION 'PURCHASE_PAYMENT_OVERPAY:total pembayaran melebihi nominal PO';
  END IF;

  -- Idempotency: kunci sama yang sudah tercatat dikembalikan tanpa duplikasi.
  IF p_idempotency_key IS NOT NULL THEN
    SELECT id INTO v_payment_id
      FROM public.purchase_order_payments
      WHERE idempotency_key = p_idempotency_key;
    IF FOUND THEN
      RETURN jsonb_build_object('payment_id', v_payment_id, 'total_paid', v_paid, 'duplicate', true);
    END IF;
  END IF;

  INSERT INTO public.purchase_order_payments (order_id, payment_date, amount, notes, idempotency_key, recorded_by)
  VALUES (p_order_id, p_payment_date, p_amount, NULLIF(trim(coalesce(p_notes, '')), ''), p_idempotency_key, p_actor)
  RETURNING id INTO v_payment_id;

  UPDATE public.purchase_orders
  SET total_paid = v_paid + p_amount, updated_at = now()
  WHERE id = p_order_id;

  INSERT INTO public.purchase_order_events (order_id, event_type, note, actor_id)
  VALUES (p_order_id, 'payment', 'Pembayaran ' || p_amount::text || ' pada ' || p_payment_date::text, p_actor);

  RETURN jsonb_build_object('payment_id', v_payment_id, 'total_paid', v_paid + p_amount, 'duplicate', false);
END;
$$;

REVOKE ALL ON FUNCTION public.record_purchase_payment(bigint, date, bigint, text, uuid, text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_purchase_payment(bigint, date, bigint, text, uuid, text) TO service_role;

